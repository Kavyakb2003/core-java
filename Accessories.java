class Accessories{
	
	public String name;
	public String brand;
	public double price;
	public String material;
	public boolean available;
	
	public Accessories()
	{
		
	}
	public Accessories(String name, String brand, double price, String material,boolean available){
		this.name = name;
		this.brand = brand;
		this.price = price;
		this.material = material;
		this.available = available;
	}
	
	
}