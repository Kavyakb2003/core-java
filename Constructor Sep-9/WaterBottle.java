class WaterBottle{

	public String brand;
	public String color;
	public double price;
	public double capacity;
	public String material;
	
	public WaterBottle()
	{
		System.out.println("Water Bottle Details:");
		
	}
	public WaterBottle(String brand,String color,double price,double capacity,String material)
	{
		this.brand = brand;
		this.color = color;
		this.price = price;
		this.capacity = capacity;
		this.material = material;
		
		
	}


}