class Coffee {
	
    public String name;
    public String type;
    public double price;
    public String size;
    public boolean hot;

    public Coffee() {
    }

    public Coffee(String name, String type, double price, String size, boolean hot) {
        this.name = name;
        this.type = type;
        this.price = price;
        this.size = size;
        this.hot = hot;
    }
}
