class Crocodile {

    public String name;
    public double length;
    public double weight;
    public String habitat;
    public boolean dangerous;

    public Crocodile() {
    }

    public Crocodile(String name, double length, double weight, String habitat, boolean dangerous) {
        this.name = name;
        this.length = length;
        this.weight = weight;
        this.habitat = habitat;
        this.dangerous = dangerous;
    }
}
