class Egg {
    public String type;
    public String color;
    public double price;
    public int quantity;
    public boolean fresh;

    public Egg() {
    }

    public Egg(String type, String color, double price, int quantity, boolean fresh) {
        this.type = type;
        this.color = color;
        this.price = price;
        this.quantity = quantity;
        this.fresh = fresh;
    }
}
