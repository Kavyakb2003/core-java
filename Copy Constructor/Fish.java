class Fish {
    public String name;
    public double weight;
    public double price;
    public String waterType;
    public boolean fresh;

    public Fish() {
    }

    public Fish(String name, double weight, double price, String waterType, boolean fresh) {
        this.name = name;
        this.weight = weight;
        this.price = price;
        this.waterType = waterType;
        this.fresh = fresh;
    }
}
