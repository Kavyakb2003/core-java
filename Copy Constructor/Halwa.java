class Halwa {
    public String name;
    public String type;
    public double price;
    public String color;
    public boolean sweet;

    public Halwa() {
    }

    public Halwa(String name, String type, double price, String color, boolean sweet) {
        this.name = name;
        this.type = type;
        this.price = price;
        this.color = color;
        this.sweet = sweet;
    }
}
