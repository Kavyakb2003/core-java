class Mutton {
    public String type;
    public double weight;
    public double price;
    public String quality;
    public boolean fresh;

    public Mutton() {
    }

    public Mutton(String type, double weight, double price, String quality, boolean fresh) {
        this.type = type;
        this.weight = weight;
        this.price = price;
        this.quality = quality;
        this.fresh = fresh;
    }
}
