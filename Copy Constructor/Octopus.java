class Octopus {
    public String type;
    public double weight;
    public double price;
    public String color;
    public boolean fresh;

    public Octopus() {
    }

    public Octopus(String type, double weight, double price, String color, boolean fresh) {
        this.type = type;
        this.weight = weight;
        this.price = price;
        this.color = color;
        this.fresh = fresh;
    }
}
