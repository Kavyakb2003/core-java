class Rabbit {
    public String name;
    public String color;
    public double weight;
    public int age;
    public boolean domestic;

    public Rabbit() {
    }

    public Rabbit(String name, String color, double weight, int age, boolean domestic) {
        this.name = name;
        this.color = color;
        this.weight = weight;
        this.age = age;
        this.domestic = domestic;
    }
}
