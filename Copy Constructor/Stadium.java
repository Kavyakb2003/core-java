class Stadium {

    public String name;
    public String location;
    public int capacity;
    public String sport;
    public boolean indoor;

    public Stadium() {
    }

    public Stadium(String name, String location, int capacity, String sport, boolean indoor) {
        this.name = name;
        this.location = location;
        this.capacity = capacity;
        this.sport = sport;
        this.indoor = indoor;
    }
}
