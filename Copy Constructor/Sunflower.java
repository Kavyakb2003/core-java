class Sunflower {
    public String color;
    public double height;
    public double price;
    public String season;
    public boolean fresh;

    public Sunflower() {
    }

    public Sunflower(String color, double height, double price, String season, boolean fresh) {
        this.color = color;
        this.height = height;
        this.price = price;
        this.season = season;
        this.fresh = fresh;
    }
}
